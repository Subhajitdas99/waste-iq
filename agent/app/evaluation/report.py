"""Evaluation report rendering — markdown table + persistence + status payload."""

from __future__ import annotations

import json
from pathlib import Path

from app.evaluation.schema import CategorySummary, EvaluationReport

_CATEGORY_LABELS = {
    "repository_search": "Repository Search",
    "architecture": "Architecture",
    "issue_assistant": "Issue Assistant",
    "pr_review": "PR Review",
    "documentation": "Documentation Agent",
    "llm_layer": "LLM Layer",
}

_MANUAL_NOTE = "manual case — human scored"


def category_label(category: str) -> str:
    return _CATEGORY_LABELS.get(category, category)


def render_markdown(report: EvaluationReport) -> str:
    """Render the full EVALUATION_RESULTS.md document from the report."""
    lines = [
        "# AI Engineering Agent — Evaluation Results",
        "",
        f"- **Benchmark version:** {report.benchmark_version}",
        f"- **Run ID:** {report.run_id}",
        f"- **Run at:** {report.ran_at}",
        f"- **Repository root:** {report.repository_root}",
        f"- **Index:** {report.index_files} files, {report.index_chunks} chunks",
        f"- **Overall score:** {report.overall_score}",
        f"- **Hallucinated citations:** {report.hallucinations}",
        f"- **Quality gates:** {'PASS' if report.gates.passed else 'FAIL'}",
        "",
        "## Quality Gates",
        "",
        "| Gate | Threshold | Value | Pass / Fail |",
        "|---|---|---|---|",
        _gate_row("Repository Search", ">= 90", _gate_value(report, "repository_search")),
        _gate_row("Grounding", "= 100", _gate_value(report, "grounding")),
        _gate_row("Hallucinations", "= 0", _gate_value(report, "hallucinations")),
        _gate_row("Overall", ">= 90", f"{report.overall_score:.1f}"),
        "",
        "## Category Summary",
        "",
        "| Category | Cases | Executed | Manual | Failed | Average | Grounding |",
        "|---|---|---|---|---|---|---|",
    ]
    for summary in report.categories:
        lines.append(_category_row(summary))
    lines += [
        "",
        "## Detailed Results",
        "",
        "| Feature | Question | Expected | Actual | Pass / Fail | Score | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for scored in report.cases:
        case, result = scored.case, scored.result
        expected = case.expected_behaviour
        if case.expected_files:
            expected += " — files: " + ", ".join(f"`{f}`" for f in case.expected_files[:3])
        if case.expected_adrs:
            expected += " — ADRs: " + ", ".join(case.expected_adrs)
        if result.status == "manual":
            lines.append(
                _row(
                    category_label(case.category),
                    case.question,
                    expected,
                    _MANUAL_NOTE,
                    "manual",
                    "",
                    "not executed automatically",
                )
            )
            continue
        if result.status == "failed":
            lines.append(
                _row(
                    category_label(case.category),
                    case.question,
                    expected,
                    "execution error",
                    "FAIL",
                    "0",
                    result.notes,
                )
            )
            continue
        passed = scored.passed
        lines.append(
            _row(
                category_label(case.category),
                case.question,
                expected,
                result.actual_answer,
                "PASS" if passed else "FAIL",
                f"{scored.final_score:.1f}",
                result.notes,
            )
        )
    lines += [
        "",
        "## Sub-Scores",
        "",
        "| Case | Repo Accuracy | Grounding | Helpfulness | Completeness | Hallucination | Final |",
        "|---|---|---|---|---|---|---|",
    ]
    for scored in report.cases:
        if scored.result.status != "executed":
            continue
        lines.append(
            f"| `{scored.case.id}` | {scored.repository_accuracy:.1f} | "
            f"{scored.grounding:.1f} | {scored.helpfulness:.1f} | "
            f"{scored.completeness:.1f} | {scored.hallucination_resistance:.1f} | "
            f"{scored.final_score:.1f} |"
        )
    lines += ["", "---", "", "Generated by `scripts/run_evaluation.py`."]
    return "\n".join(lines)


def _gate_value(report: EvaluationReport, kind: str) -> str:
    if kind == "repository_search":
        return f"{report.category_average('repository_search'):.1f}"
    if kind == "grounding":
        # Per-case grounding sub-scores are 0-10 internally; gates and the
        # markdown table use the 0-100 scale, so convert at the boundary.
        executed = [c for c in report.cases if c.result.status == "executed"]
        if not executed:
            return "-"
        value = round(sum(c.grounding for c in executed) / len(executed), 2)
        return f"{value * 10:.1f}"
    return str(getattr(report, kind))


def _category_row(summary: CategorySummary) -> str:
    return (
        f"| {category_label(summary.category)} | {summary.cases} | "
        f"{summary.executed} | {summary.manual} | {summary.failed} | "
        f"{summary.average:.1f} | {summary.grounding:.1f} |"
    )


def _gate_row(name: str, threshold: str, value: str) -> str:
    passed = False
    try:
        if name == "Repository Search":
            passed = float(value) >= 90.0
        elif name == "Grounding":
            passed = float(value) == 100.0
        elif name == "Hallucinations":
            passed = int(value) == 0
        else:
            passed = float(value) >= 90.0
    except ValueError:
        passed = False
    return f"| {name} | {threshold} | {value} | {'PASS' if passed else 'FAIL'} |"


def _row(*cells: str) -> str:
    return "| " + " | ".join(cells) + " |"


def save_report(report: EvaluationReport, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(report), encoding="utf-8")
    return path


def save_json(report: EvaluationReport, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(report.model_dump(mode="json"), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return path


def load_json(path: str | Path) -> EvaluationReport | None:
    path = Path(path)
    if not path.exists():
        return None
    try:
        return EvaluationReport.model_validate(json.loads(path.read_text(encoding="utf-8")))
    except Exception:  # noqa: BLE001 - corrupt state must not crash status
        return None


def status_payload(report: EvaluationReport) -> dict:
    """Compact status document for /api/evaluation/status and CI."""
    executed = [c for c in report.cases if c.result.status == "executed"]
    categories = [c for c in report.categories if c.executed > 0]
    weakest = min(categories, key=lambda c: c.average) if categories else None
    strongest = max(categories, key=lambda c: c.average) if categories else None
    return {
        "benchmark_version": report.benchmark_version,
        "last_run": report.ran_at,
        "run_id": report.run_id,
        "overall_score": report.overall_score,
        "failures": sum(1 for c in executed if not c.passed),
        "cases_executed": len(executed),
        "hallucinations": report.hallucinations,
        "weakest_category": weakest.category if weakest else None,
        "strongest_category": strongest.category if strongest else None,
        "gates": {
            "repository_search_ge_90": report.gates.repository_search_ge_90,
            "grounding_eq_100": report.gates.grounding_eq_100,
            "hallucinations_zero": report.gates.hallucinations_zero,
            "overall_ge_90": report.gates.overall_ge_90,
            "passed": report.gates.passed,
        },
    }


def load_state(path: str | Path) -> dict | None:
    path = Path(path)
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001 - corrupt state must not crash status
        return None


def save_state(report: EvaluationReport, path: str | Path) -> dict:
    payload = status_payload(report)
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return payload
